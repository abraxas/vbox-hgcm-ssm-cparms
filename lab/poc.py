def clip(text: str, limit: int = 240) -> str:
    compact = text.replace("\r\n", "\\n").replace("\n", "\\n")
    if len(compact) > limit:
        return compact[:limit] + "..."
    return compact


def http_get(path: str) -> HttpExchange:
    url = f"http://{HOST}:{PORT}{path}"
    req = Request(url, method="GET")
    try:
        with urlopen(req, timeout=HTTP_TIMEOUT_S) as resp:
            body = resp.read().decode("utf-8", "replace")
            status = int(resp.status)
    except HTTPError as exc:
        body = exc.read().decode("utf-8", "replace")
        status = int(exc.code)
    except (URLError, TimeoutError, OSError) as exc:
        return HttpExchange(status=0, body="", error=f"{type(exc).__name__}:{exc}")

    parsed: dict[str, Any] | None = None
    try:
        loaded = json.loads(body)
    except json.JSONDecodeError:
        loaded = None
    if isinstance(loaded, dict):
        parsed = loaded
    return HttpExchange(status=status, body=body, parsed=parsed)


def as_int(payload: dict[str, Any], key: str) -> int | None:
    value = payload.get(key)
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, str) and value.isdigit():
        return int(value)
    return None


